describe('scancodeFor', () => {
  it('lists 125 distinct codes', () => {
    expect(ROWS).toHaveLength(125)
    expect(new Set(ROWS.map(([code]) => code)).size).toBe(125)
  })

  it.each(ROWS)('maps %s to scancode %d, extended %s', (code, scancode, extended) => {
    expect(scancodeFor(code)).toEqual({ code: scancode, extended })
  })

  it('keeps every scancode within 1..0x7f', () => {
    for (const [code, scancode] of ROWS) {
      expect(scancode, code).toBeGreaterThanOrEqual(1)
      expect(scancode, code).toBeLessThanOrEqual(0x7f)
    }
  })

  it('gives no two codes the same scancode and extended flag', () => {
    const seen = new Map<string, string>()
    for (const [code] of ROWS) {
      const found = scancodeFor(code)
      const key = `${found?.extended ? 'e0' : ''}${found?.code}`
      expect(seen.get(key), `${code} and ${seen.get(key)}`).toBeUndefined()
      seen.set(key, code)
    }
    expect(seen.size).toBe(ROWS.length)
  })

  it.each(UNMAPPED)('gives null for %j', (code) => {
    expect(scancodeFor(code)).toBeNull()
  })
})
