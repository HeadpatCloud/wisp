import { expect, test } from 'vitest'
import { parseItermColors, parseWindowsTerminal, terminalColorsFor } from './schemes'
import { BUILT_IN_THEMES } from './themes'

const WT = {
  name: 'Campbell',
  background: '#0C0C0C',
  foreground: '#CCCCCC',
  cursorColor: '#FFFFFF',
  selectionBackground: '#FFFFFF',
  black: '#0C0C0C',
  red: '#C50F1F',
  green: '#13A10E',
  yellow: '#C19C00',
  blue: '#0037DA',
  purple: '#881798',
  cyan: '#3A96DD',
  white: '#CCCCCC',
  brightBlack: '#767676',
  brightRed: '#E74856',
  brightGreen: '#16C60C',
  brightYellow: '#F9F1A5',
  brightBlue: '#3B78FF',
  brightPurple: '#B4009E',
  brightCyan: '#61D6D6',
  brightWhite: '#F2F2F2',
}

test('windows_terminal_schemes_import', () => {
  const [one] = parseWindowsTerminal(JSON.stringify(WT))
  expect(one).toMatchObject({ name: 'Campbell' })
  expect(one.colors).toMatchObject({
    background: '#0C0C0C',
    magenta: '#881798',
    brightMagenta: '#B4009E',
    cursor: '#FFFFFF',
  })
  const two = parseWindowsTerminal(JSON.stringify({ schemes: [WT, { ...WT, name: 'Other' }] }))
  expect(two.map((s) => s.name)).toEqual(['Campbell', 'Other'])
  expect(() => parseWindowsTerminal(JSON.stringify({ name: 'x' }))).toThrow(
    'background is missing.',
  )
})

test('windows_terminal_settings_files_import', () => {
  const { selectionBackground: _, ...noSelection } = { ...WT, name: 'No selection' }
  // Windows Terminal writes JSON with comments and trailing commas.
  const settings = `// This file was initially generated by Windows Terminal
{
  "$schema": "https://aka.ms/terminal-profiles-schema",
  /* profiles, keybindings, ... */
  "profiles": { "list": [], },
  "schemes": [
    ${JSON.stringify(noSelection)}, // one without a selection colour
    ${JSON.stringify(WT)},
  ],
}`
  const [first, second] = parseWindowsTerminal(settings)
  expect(first.name).toBe('No selection')
  expect(first.colors.selectionBackground).toBe('#CCCCCC66')
  expect(second.colors.selectionBackground).toBe('#FFFFFF')
  expect(() =>
    parseWindowsTerminal(JSON.stringify({ name: 'Broken', foreground: '#FFFFFF' })),
  ).toThrow('Broken: background is missing.')
})

const colour = (r: number, g: number, b: number) => `<dict>
  <key>Blue Component</key><real>${b}</real>
  <key>Green Component</key><real>${g}</real>
  <key>Red Component</key><real>${r}</real>
</dict>`

test('iterm2_schemes_import', () => {
  const ansi = Array.from(
    { length: 16 },
    (_, i) => `<key>Ansi ${i} Color</key>${colour(i / 15, 0, 1 - i / 15)}`,
  )
  const plist = `<?xml version="1.0" encoding="UTF-8"?>
<plist version="1.0"><dict>
  ${ansi.join('\n')}
  <key>Background Color</key>${colour(0, 0, 0)}
  <key>Foreground Color</key>${colour(1, 1, 1)}
  <key>Cursor Color</key>${colour(1, 0.5, 0)}
  <key>Selection Color</key>${colour(0.2, 0.2, 0.2)}
</dict></plist>`
  const s = parseItermColors(plist, 'Solar.itermcolors')
  expect(s.name).toBe('Solar')
  expect(s.colors).toMatchObject({
    background: '#000000',
    foreground: '#ffffff',
    cursor: '#ff8000',
    black: '#0000ff',
    brightWhite: '#ff0000',
  })
  expect(() => parseItermColors('<plist><dict></dict></plist>', 'x.itermcolors')).toThrow(
    'Ansi 0 Color is missing.',
  )
})

test('terminal_colours_win_in_spec_order', () => {
  const paper = BUILT_IN_THEMES[0]
  const ctx = { schemes: [], themes: BUILT_IN_THEMES, active: paper }
  const from = (connection: string | null, tag: string | null, setting: string) =>
    terminalColorsFor({ connection, tag, setting }, ctx).background
  const dracula = '#282a36'
  const nord = '#2e3440'
  // The connection first, then the first tag with colours, then the setting.
  expect(from('dracula', 'nord', 'gruvbox')).toBe(dracula)
  expect(from(null, 'nord', 'gruvbox')).toBe(nord)
  expect(from(null, null, 'dracula')).toBe(dracula)
  // "From the theme" is the active theme's terminal colours.
  expect(from(null, null, 'default')).toBe(paper.terminal.background)
  // 0.5.0's light and dark mean Paper's and Graphite's terminals; theme:<id> names any theme.
  const graphite = BUILT_IN_THEMES[1]
  expect(from('dark', null, 'default')).toBe(graphite.terminal.background)
  expect(from('theme:graphite', null, 'default')).toBe(graphite.terminal.background)
  // Something that no longer exists falls through to the next.
  expect(from('gone', null, 'nord')).toBe(nord)
})
